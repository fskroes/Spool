#!/bin/bash
# Generates the Raycast script commands in this folder from the list below.
# Run it again after you change the list: bash Integrations/Raycast/generate.sh
# Each name must be a command from `spool list` (or "state"). SpoolCoreTests checks this.
set -euo pipefail

dir="$(cd "$(dirname "$0")" && pwd)"
marker="Generated by generate.sh"

# name | title | icon | launch (yes: if Spool is not running, open it and run the command)
commands='
focus-left|Focus Left|⬅️|yes
focus-right|Focus Right|➡️|yes
focus-up|Focus Up in Stack|⬆️|yes
focus-down|Focus Down in Stack|⬇️|yes
move-left|Move Column Left|⏪|yes
move-right|Move Column Right|⏩|yes
cycle-width|Cycle Column Width|↔️|yes
toggle-full-width|Full Width Column|🔲|yes
center-column|Center Column|🎯|yes
toggle-tabbed|Tabbed Column|🗂️|yes
stack-left|Stack Into Left Column|📥|yes
stack-right|Stack Into Right Column|📥|yes
pop-left|Pop Out of Stack to the Left|📤|yes
pop-right|Pop Out of Stack to the Right|📤|yes
toggle-float|Float or Unfloat Window|🪟|yes
send-to-next-display|Send Window to Next Display|🖥️|yes
start|Start Window Manager|▶️|yes
stop|Stop Window Manager|⏹️|no
restart|Restart Window Manager|🔄|yes
toggle-engine|Start or Stop Window Manager|⏯️|yes
'

# Remove old generated scripts, so a name removed from the list does not stay behind.
for f in "$dir"/spool-*.sh; do
  [ -e "$f" ] || continue
  grep -q "$marker" "$f" && rm -f "$f"
done

find_cli='find_cli() {
  command -v spool 2>/dev/null && return
  # Raycast does not load your shell profile, so also look in the usual places.
  for p in "$HOME/.local/bin/spool" /Applications/Spool.app/Contents/Helpers/spool; do
    if [ -x "$p" ]; then echo "$p"; return; fi
  done
}'

count=0
while IFS='|' read -r name title icon launch; do
  [ -n "$name" ] || continue
  if [ "$launch" = yes ]; then
    note='# Exit code 3: Spool is not running. The URL opens Spool and runs the command.'
    not_running='open -g "spool://$cmd"'
  else
    note='# Exit code 3: Spool is not running, so there is nothing to do.'
    not_running='echo "Spool is not running."'
  fi
  cat > "$dir/spool-$name.sh" <<EOF
#!/bin/bash

# Required parameters:
# @raycast.schemaVersion 1
# @raycast.title $title
# @raycast.mode silent
# @raycast.packageName Spool

# Optional parameters:
# @raycast.icon $icon
# @raycast.description $title. Runs: spool $name

# $marker. Do not edit: change the list in generate.sh and run it again.

cmd="$name"

$find_cli

cli="\$(find_cli)"
if [ -z "\$cli" ]; then
  # No CLI: the URL scheme runs the same command (and opens Spool if needed).
  open -g "spool://\$cmd"
  exit
fi
out="\$("\$cli" "\$cmd" 2>&1)"
status=\$?
if [ "\$status" -ne 3 ]; then
  [ -z "\$out" ] || echo "\$out"
  exit "\$status"
fi
$note
$not_running
EOF
  chmod +x "$dir/spool-$name.sh"
  count=$((count + 1))
done <<< "$commands"

cat > "$dir/spool-state.sh" <<EOF
#!/bin/bash

# Required parameters:
# @raycast.schemaVersion 1
# @raycast.title Spool State
# @raycast.mode fullOutput
# @raycast.packageName Spool

# Optional parameters:
# @raycast.icon ℹ️
# @raycast.description Show displays, columns and windows. Runs: spool state

# $marker. Do not edit: change generate.sh and run it again.

cmd="state"

$find_cli

cli="\$(find_cli)"
if [ -z "\$cli" ]; then
  echo "The spool command-line tool is not installed. Run 'make install' in the Spool source folder."
  exit 1
fi
"\$cli" "\$cmd" 2>&1
EOF
chmod +x "$dir/spool-state.sh"
count=$((count + 1))

echo "Wrote $count scripts to $dir"
